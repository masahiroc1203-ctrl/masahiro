// anim: お手本アニメの定義（js/pose.js 参照）
//   view: 'side'（右向きの横から）| 'front'（正面から）
//   ms:   1サイクルの長さ
//   k:    キーフレーム配列。hip=[x,y] 腰の位置, t=胴体の角度, nk=首の角度,
//         a1/a2=手前/奥の腕（正面ビューでは画面右/左）, l1/l2=脚
//         h=そのフレームで止まる比率, d=次への移行比率, j=移行中のジャンプ高さ
// lr:  'alt' = 左右交互, 'switch' = 時間の半分で左右を入れ替える

const G = 92; // 床に接する関節のy座標（床の線 94 − 線の太さ/2）
const at = (x, y = G, b) => (b === undefined ? { p: [x, y] } : { p: [x, y], b });
const rotArm = (a, d) => (Array.isArray(a) ? [a[0] + d, a[1] + d] : a);
// 上半身（胴体・首・腕）をまとめて回転
const rot = (pose, d) => ({
  ...pose,
  t: pose.t + d,
  nk: (pose.nk ?? pose.t) + d,
  a1: rotArm(pose.a1, d),
  a2: rotArm(pose.a2, d),
});

